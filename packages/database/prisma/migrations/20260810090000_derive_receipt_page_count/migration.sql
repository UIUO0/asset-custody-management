-- عدد الصفحات صار مشتقاً من عدد أسطر النموذج لا مكتوباً بيد الموظف.
--
-- الصفوف القائمة كُتبت يدوياً قبل التغيير، وفيها ما يخالف الواقع: نموذج
-- من سطرين يقول إنه ١١ صفحة، وآخر بلا قيمة أصلاً. الرقم يُطبع على مستند
-- موقَّع، فتركُه على حاله يعني وثيقة تناقض الورق الذي بين يدي من يوقّعها.
--
-- القاعدة هي نفسها التي ينفّذها `app/modules/goods-receipt/pagination.ts`
-- (ITEM_LINES_PER_PAGE = 12، وبحد أدنى صفحة واحدة). أي تغيير هناك يستلزم
-- ترحيلاً مماثلاً هنا — الرقم مخزَّن لا محسوب عند القراءة، لأنه يجب أن يبقى
-- كما كان يوم وُقّع المستند.
--
-- ترحيل بيانات فقط: لا تغيير في المخطط، فلا جمل مولَّدة ولا فهارس تُمسّ.
UPDATE "GoodsReceipt" g
SET "pageCount" = GREATEST(
  1,
  CEIL(
    COALESCE((SELECT COUNT(*) FROM "GoodsReceiptLine" l WHERE l."receiptId" = g.id), 0)::numeric / 12
  )::int
);
